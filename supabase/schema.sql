create or replace function public.record_game_download(p_game_id text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    if p_game_id is null or p_game_id !~ '^[a-z0-9-]{1,80}$' then
        raise exception 'Invalid game id.';
    end if;

    if not exists (select 1 from public.game_catalog where id = p_game_id) then
        raise exception 'Unknown game id.';
    end if;

    insert into public.game_download_clicks (user_id, game_id, click_day, created_at)
    values (auth.uid(), p_game_id, (now() at time zone 'utc')::date, now());
end;
$$;

create or replace function public.get_top_downloaded_game()
returns table (game_id text, clicks bigint)
language sql
security definer
set search_path = ''
as $$
    select clicks.game_id, count(*)::bigint as clicks
    from public.game_download_clicks as clicks
    group by clicks.game_id
    order by count(*) desc, clicks.game_id asc
    limit 3;
$$;

create or replace function public.get_download_dashboard_stats()
returns table (game_id text, total_clicks bigint, clicks_today bigint, clicks_7d bigint)
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not exists (
        select 1
        from public.dashboard_admins as admin
        where admin.email = lower(coalesce(auth.jwt() ->> 'email', ''))
    ) then
        raise exception 'Dashboard access denied.' using errcode = '42501';
    end if;

    return query
    select
        catalog.id,
        count(clicks.id)::bigint,
        count(clicks.id) filter (where clicks.click_day = (now() at time zone 'utc')::date)::bigint,
        count(clicks.id) filter (where clicks.click_day >= (now() at time zone 'utc')::date - 6)::bigint
    from public.game_catalog as catalog
    left join public.game_download_clicks as clicks on clicks.game_id = catalog.id
    group by catalog.id
    order by count(clicks.id) desc, catalog.id asc;
end;
$$;

create or replace function public.get_download_daily_stats()
returns table (day date, clicks bigint)
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not exists (
        select 1
        from public.dashboard_admins as admin
        where admin.email = lower(coalesce(auth.jwt() ->> 'email', ''))
    ) then
        raise exception 'Dashboard access denied.' using errcode = '42501';
    end if;

    return query
    select days.day::date, count(clicks.id)::bigint
    from generate_series(
        ((now() at time zone 'utc')::date - 6)::timestamp,
        (now() at time zone 'utc')::date::timestamp,
        interval '1 day'
    ) as days(day)
    left join public.game_download_clicks as clicks
        on clicks.click_day = days.day::date
    group by days.day
    order by days.day;
end;
$$;

